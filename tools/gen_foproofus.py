#!/usr/bin/env python3
# tests/foproofus-progs<i>.cub (i = 1 .. 4, a few programs each, every part on a line of its own): for every program of experiments/fo/run.py's proved-* programs (the data route's,
# as tools/gen_foproofq.py lists them), the checked path from its source to the unboxed C (lib/foproofus.cub,
# U3), composed with the boxed link's: the unboxed C functions (P-GU: each key's first-order body translated
# by fq-to-cu at U1's tables P-S, lib/foproofcu.cub's fq-to-cu-def), the closure targets (P-dc) and the
# dispatcher's keys (P-CD), the obligations decided over the keys (ukeys-ok), and P-upath: at every fuel and
# arguments, the source's value refined by the first-order form's (lib/foproofq.cub's q-path-n), refined by
# the boxed C's on C's words (lib/foproofm.cub's cm-sound-t, a limit hit or refined) and by the unboxed C's
# (cu-sound-k, a limit hit or refined). P-uword reads it at a word: when the first-order form answers a word,
# both C programs answer it or hit a limit (cu-agree). Readings: the unboxed C's meaning at run.py's
# arguments is run.py's answer, and each unboxed function of the instance is the one the UNBOXED route
# prints (lib/foproofcu.cub's cu-tr of the harness's program) at its key. For the two word programs,
# ex-upath and fib-upath (cu-fw-path).
# Builds on tests/foproofq-progs.cub (the tables, P-gok, P-gq, loaded first); U1's definitions of each program
# (the keys P-uks, P-udf, P-uAN, the arguments' kinds P-MK, the kinds P-S, and the data types' indices) are copied
# from tests/foproofu-progs.cub, so a part loads without that file's kind-sound instances.
# To rerun (after a program, the mirror or the kinds change, and after rerunning tools/gen_foproofq.py and
# tools/gen_foproofu.py): `python3 tools/gen_foproofus.py` from scoped-machine/ writes the parts.
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'experiments', 'fo'))
import gen_foproofq as gq
import run as RUN
# the data route's program name in run.py for each instance
RUNNAME = {'qp-spec': 'proved-spec', 'qp-region': 'proved-region', 'qp-cmp': 'proved-cmp', 'qp-tags': 'proved-tags', 'qp-list': 'proved-list',
           'qp-loop': 'proved-loop', 'qp-num': 'proved-num', 'qp-float': 'proved-float', 'qp-calls': 'proved-calls', 'qp-bytes': 'proved-bytes',
           'qp-bytes32': 'proved-bytes32', 'qp-data': 'proved-data', 'qp-pair': 'proved-pair'}

PARTS = [['qp-spec', 'qp-region', 'qp-cmp', 'qp-tags'], ['qp-list', 'qp-loop', 'qp-num'], ['qp-float', 'qp-calls', 'qp-bytes', 'qp-bytes32'], ['qp-data', 'qp-pair']]

def gen(part):
    up = open(os.path.join(ROOT, 'tests', 'foproofu-progs.cub')).read()
    R = '(fst std-frule)'
    o = ['-- generated by tools/gen_foproofus.py (do not edit: rerun it); loaded after tests/foproofq-progs.cub']
    o.append('obs-u v = case v of mw w → some w; mlim → some #18446744073709551616; _ → none')
    o += [l for l in up.split('\n') if l.startswith('#same didx')]
    for (name, sp, fargs, expect) in gq.PROGS:
        if name not in PARTS[part]: continue
        P = name
        o.append('-- %s: U1\'s definitions (from tests/foproofu-progs.cub)' % P)
        for suf in ['uks', 'udf', 'uAN', 'MK', 'S']:
            o += [l for l in up.split('\n') if l.startswith('%s-%s :' % (P, suf)) or l.startswith('%s-%s ' % (P, suf)) and ' = ' in l and not l.startswith('%s-%s :' % (P, suf))][:2]
        m = re.search(r'^%s-S = kinfer .* \(fc-to-fq (\d+) ' % re.escape(P), up, re.M)
        if not m: sys.exit('gen_foproofus: no kinds for %s in tests/foproofu-progs.cub' % P)
        k = int(m.group(1))
        keys = re.search(r'^%s-uks = (.*)$' % re.escape(P), up, re.M).group(1)
        klist = re.findall(r'\(wadd dcbase #\d+\)|#\d+', keys)
        FT = '(q-ft (fr-tab %s %s-T) (fr-tab %s %s-GT) %s-D %s-A)' % (R, P, R, P, P, P)
        MQ = '(fc-to-fq %d (fr-bu %s (dconv %s-m)))' % (k, R, P)
        S = '%s-S' % P; AN = '%s-uAN' % P; DF = '%s-udf' % P; KS = '%s-uks' % P
        G0 = '(kpush %s-MK (λ n → ka))' % P
        MC = '(λ l → ct-of (knth %s-MK l))' % P
        MW = '(λ i → ct-of (ksyn %s %s kmt %s))' % (S, MQ, G0)
        MU = '(fq-to-cu %s %s ckt %s %s %d %s)' % (S, MQ, G0, MC, k, MW)
        o.append('-- %s: the unboxed C link' % P)
        o.append('%s-GU : Word → CU' % P)
        o.append('%s-GU g = fq-to-cu-def %s g (%s g) (%s g)' % (P, S, AN, FT))
        o.append('%s-GCb : Word → CA' % P)
        o.append('%s-GCb g = fq-to-ca (%s g) ckt (%s g)' % (P, FT, AN))
        cks = [x for x in klist if x.startswith('(wadd')]
        cl = 'nil'
        for x in reversed(cks): cl = '(cons %s %s)' % (x, cl)
        o.append('%s-cks : List Word' % P)
        o.append('%s-cks = %s' % (P, cl))
        o.append('%s-dc : Word → Bool' % P)
        o.append('%s-dc g = kmemu g %s-cks' % (P, P))
        o.append('%s-hdf : (g : Word) → %s-dc g ≡ true → %s g ≡ true' % (P, P, DF))
        o.append('%s-hdf = ukeys-ok (λ x → kmemu x %s) %s-cks (λ i → true)' % (P, KS, P))
        o.append('%s-hsk : (g : Word) → %s-dc g ≡ true → ks-SK %s g ≡ kanys (%s g)' % (P, P, S, AN))
        o.append('%s-hsk g h = kanysb-ok (ks-SK %s g) (%s g) (ukeys-ok (λ x → kanysb (ks-SK %s x) (%s x)) %s-cks (λ i → true) g h)' % (P, S, AN, S, AN, P))
        o.append('%s-kko : kkeys-ok %s %s %s %s ≡ true' % (P, S, DF, FT, KS))
        o.append('%s-kko = λ i → true' % P)
        o.append('%s-utok : (g : Word) → %s g ≡ true → uok %s %s %s-dc (%s g) ckt ≡ true' % (P, DF, AN, DF, P, FT))
        o.append('%s-utok = ukeys-ok (λ g → uok %s %s %s-dc (%s g) ckt) %s (λ i → true)' % (P, AN, DF, P, FT, KS))
        o.append('%s-ctok : (g : Word) → %s g ≡ true → ca-ok %s %s (%s g) ckt ≡ true' % (P, DF, AN, DF, FT))
        o.append('%s-ctok = ukeys-ok (λ g → ca-ok %s %s (%s g) ckt) %s (λ i → true)' % (P, AN, DF, FT, KS))
        kok_g = '(kok %s %s (%s g) kmt (spk %s g))' % (S, DF, FT, S)
        kle_g = '(kle (ksyn %s (%s g) kmt (spk %s g)) (ks-SR %s g))' % (S, FT, S, S)
        kk = '(kkeys-ok-k %s %s %s %s %s-kko g h)' % (S, DF, FT, KS, P)
        o.append('%s-utk : (g : Word) → %s g ≡ true → %s ≡ true' % (P, DF, kok_g))
        o.append('%s-utk g h = andl %s %s %s' % (P, kok_g, kle_g, kk))
        o.append('%s-utl : (g : Word) → %s g ≡ true → %s ≡ true' % (P, DF, kle_g))
        o.append('%s-utl g h = andr %s %s %s' % (P, kok_g, kle_g, kk))
        xs = ['x%d' % j for j in range(1, k + 1)]; vs = ['v%d' % j for j in range(1, k + 1)]
        qa = 'qa0'
        for j in range(k): qa = '(qa1 %s %s %s)' % (xs[j], vs[j], qa)
        ev = 'kqnil'
        for j in range(k): ev = '(kqcons %s %s)' % (vs[j], ev)
        binds = ''.join(' (%s : DV) (%s : KQ)' % (xs[j], vs[j]) for j in range(k))
        pas = ''.join(' %s %s' % (xs[j], vs[j]) for j in range(k))
        EQ = '(evq %s (fr-addn n m) %s %s)' % (FT, MQ, ev)
        SRC = '(derase (dsev %s-G n %s-m (qa-ρ %s)))' % (P, P, qa)
        EC = '(evc %s-GCb %s %s (fr-addn n m) (fq-to-ca %s ckt %d) (c2ms s))' % (P, AN, DF, MQ, k)
        EU = '(evcu %s-GU %s %s-dc (fr-addn n m) %s su)' % (P, AN, P, MU)
        CS = ('cu-sound-k %s %s %s %s-dc %s-dc %s %s-GU (λ g h → h) %s-hdf %s-hsk %s-utok %s-utk %s-utl (λ g h → λ i → %s-GU g)'
              % (S, AN, DF, P, P, FT, P, P, P, P, P, P, P))
        o.append('-- the checked path to the unboxed C: at every fuel, whatever the source computes at the arguments, the first-order')
        o.append('-- form computes (refined), the boxed C on its words computes it (a limit hit or refined), and the unboxed C computes')
        o.append('-- it (a limit hit or refined), in every refining scope whose values have the arguments\' kinds')
        o.append('%s-upath : (n : Nat)%s (m : Nat) (s : CS) (su : MSt) → qa-ok %s-D %s-T %s → Corr %s %s %d %s s → UCorr %s %s-dc %d %s su → EnvK (ks-T %s) %s %s'
                 % (P, binds, P, P, qa, AN, DF, k, ev, AN, P, k, ev, S, G0, ev))
        o.append('  → qrel %s-D %s %s × (CRC %s %s %s %s × UR %s %s-dc %s %s)' % (P, SRC, EQ, AN, DF, EQ, EC, AN, P, EQ, EU))
        o.append('%s-upath n%s m s su ha hc hu he =' % (P, pas))
        o.append('  (q-path-n std-frule %s-G %s-T %s-GT %s-gok %s-D %s-A %s-gq n %s-m %s m (dtok-auto %s-T %s-m (λ j → true)) ha (λ j → true) ,'
                 % (P, P, P, P, P, P, P, P, qa, P, P))
        o.append('   (cm-sound-t %s %s %s %s %s-GCb (λ g h → h) %s-ctok (λ g h → λ i → %s-GCb g) (fr-addn n m) %s %d %s s (λ i → true) hc ,'
                 % (AN, DF, DF, FT, P, P, P, MQ, k, ev))
        o.append('    %s (fr-addn n m) %s %s %s %d %s su (λ i → true) (λ i → true) hu he))' % (CS, MQ, G0, MC, k, ev))
        o.append('-- at a word: when the first-order form answers w, the boxed and the unboxed C each answer w or hit a limit')
        o.append('%s-uword : (n : Nat)%s (m : Nat) (s : CS) (su : MSt) (w : Word) → qa-ok %s-D %s-T %s → Corr %s %s %d %s s → UCorr %s %s-dc %d %s su → EnvK (ks-T %s) %s %s'
                 % (P, binds, P, P, qa, AN, DF, k, ev, AN, P, k, ev, S, G0, ev))
        o.append('  → %s ≡ kqw w → Sum (haslim %s ≡ true) (%s ≡ mw w) × Sum (haslim %s ≡ true) (%s ≡ mw w)' % (EQ, EC, EC, EU, EU))
        o.append('%s-uword n%s m s su w ha hc hu he hw =' % (P, pas))
        o.append('  cu-agree %s %s %s-dc w %s %s (subst {lzero} {lzero} {KQ} {λ v → CRC %s %s v %s} {%s} {kqw w} hw (fst (snd (%s-upath n%s m s su ha hc hu he))))'
                 % (AN, DF, P, EC, EU, AN, DF, EC, EQ, P, pas))
        o.append('    (subst {lzero} {lzero} {KQ} {λ v → UR %s %s-dc v %s} {%s} {kqw w} hw (snd (snd (%s-upath n%s m s su ha hc hu he))))' % (AN, P, EU, EQ, P, pas))
        # readings: the unboxed meaning at run.py's arguments, and the route's printed functions
        if fargs:
            args = 'lnil'
            for a in reversed(fargs): args = '(lcons (%s) %s)' % (a, args)
            st = '(ms-push (evcu %s-GU %s %s-dc (dnat #64) (fq-to-cu %s (fo-args-fq %s) ckl (λ n → ka) (λ l → ctb) zero (λ i → ctb)) msnil) zero msnil)' % (P, AN, P, S, args)
        else:
            st = 'msnil'
        o.append('#same obs-u (evcu %s-GU %s %s-dc (dnat #64) %s %s) = some #%s' % (P, AN, P, MU, st, expect))
        rn = RUNNAME[name]
        rargs, qd = RUN.QROUTE[rn]
        ds = '(%s)' % qd if rargs is None else '(cu-harness (fo-args-fq (%s)) (%s))' % (rargs, qd)
        o.append('%s-uds = %s' % (P, ds))
        o.append('%s-utr = cu-tr %s-uds' % (P, P))
        for kk_ in klist:
            kt = kk_.replace('wadd dcbase', '%wadd dc-base')
            o.append('#same cu-tg %s-utr %s = %s-GU %s' % (P, kt, P, kk_))
    if part == len(PARTS) - 1:
        o.append('-- the word route: no table; the main of one word parameter')
        for nm, c in [('ex', 'ex-c'), ('fib', 'fib-c')]:
            M = '(fw-to-fq (spec-w std-vrule %s))' % c
            o.append('%s-uS : KS' % nm)
            o.append('%s-uS = kinfer (λ g → fqnet) nil (λ g → zero) %s (kcons kw knil)' % (nm, M))
            o.append('%s-upath : (x : Word) (N : Nat) → kq-nb (evq (λ g → fqnet) N %s (kqcons (kqw x) kqnil))' % (nm, M))
            o.append('  → Sum (haslim (evcu (λ g → cuunsup) (λ g → zero) (λ g → false) N (fq-to-cu %s-uS %s ckt cu-g1 cu-c1 (suc zero) (λ i → ct-of (ksyn %s-uS %s kmt cu-g1))) (msb zero (mw x) msnil)) ≡ true)' % (nm, M, nm, M))
            o.append('        (evcu (λ g → cuunsup) (λ g → zero) (λ g → false) N (fq-to-cu %s-uS %s ckt cu-g1 cu-c1 (suc zero) (λ i → ct-of (ksyn %s-uS %s kmt cu-g1))) (msb zero (mw x) msnil) ≡ mw (wc-ev %s (envx x)))' % (nm, M, nm, M, c))
            o.append('%s-upath x N hn = cu-fw-path %s-uS std-vrule %s x N (λ j → true) (λ j → true) hn' % (nm, nm, c))
            # the unboxed C's meaning at an argument: run.py's proved (ex at 4: 13), fib at 30
            x, want = {'ex': ('#4', '#13'), 'fib': ('#30', '#832040')}[nm]
            o.append('#same obs-u (evcu (λ g → cuunsup) (λ g → zero) (λ g → false) (dnat #64) (fq-to-cu %s-uS %s ckt cu-g1 cu-c1 (suc zero) (λ i → ct-of (ksyn %s-uS %s kmt cu-g1))) (msb zero (mw %s) msnil)) = some %s' % (nm, M, nm, M, x, want))
    return '\n'.join(o) + '\n'

if __name__ == '__main__':
    for i in range(len(PARTS)):
        open(os.path.join(ROOT, 'tests', 'foproofus-progs%d.cub' % (i + 1)), 'w').write(gen(i))
