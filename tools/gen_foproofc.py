#!/usr/bin/env python3
# tests/foproofc-progs.cub: for every program of experiments/fo/run.py's proved-* programs, the checked
# path from its source to the C (lib/foproofc.cub's CA) the back end prints. It builds on the instances
# tests/foproofq-progs.cub defines (loaded first; the tables P-G, P-T, P-GT, P-D, P-A and the proofs
# P-gok, P-gq): the table's keys as a list (P-ks), the C functions' parameter counts (P-AN), the C
# functions (P-GC, fq-to-ca of the first-order table at each key), the table's obligations decided over
# the keys (keys-ok), and ca-path-n instantiated (P-cpath: at every fuel and arguments, the source's
# value refined by the first-order form's, refined by the C's). Readings tie the instance to what the
# proved route prints: every C function of the table run.py's program prints equal to the instance's
# at its key, the main's too, and the C's meaning computes run.py's answer at its arguments.
# To rerun (after a program or the mirror changes): `python3 tools/gen_foproofc.py > tests/foproofc-progs.cub`
# from scoped-machine/ with build/cubical built (it reruns tools/gen_foproofq.py's machine readings).
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_foproofq as gq

# the first-order table the proved route hands to the C link, as checked terms (lib/foproofc.cub's
# specialize-proved-q, or the data mirror's table for the readings taken from a code as written)
QTAB = {
    'qp-calls': 'dc-prog-defs-q (fromopt (dc-prog dq-c8) dc-dflt)',
    'qp-data': 'dc-defs-q dx-prog',
}
def qtab(name, sp):
    if name in QTAB: return QTAB[name]
    return sp[1].replace('snd (specialize-proved ', 'snd (specialize-proved-q ', 1)

def gen():
    probe = gq.PRELUDE + ''.join('#show %s\n' % p[1][0] for p in gq.PROGS)
    readings = gq.run_machine(probe)
    R = '(fst std-frule)'
    o = ['-- generated by tools/gen_foproofc.py (do not edit: rerun it); loaded after tests/foproofq-progs.cub']
    for (name, sp, fargs, expect), r in zip(gq.PROGS, readings):
        t = gq.unwrap(gq.parse(gq.tokens(r))[0])
        tup = gq.unwrap(gq.args(t)[0])
        K, main, gs = [gq.unwrap(x) for x in tup[1]]
        k = int(gq.text(K).lstrip('#'))
        defs = []
        g = gs
        while gq.head(g) == 'lcons':
            e = gq.unwrap(gq.args(g)[0])
            gk, ga, gb = [gq.unwrap(x) for x in e[1]]
            defs.append((gq.text(gk), gq.text(ga), gq.text(gb)))
            g = gq.args(g)[1]
        L = []
        gq.lams(main, k, L)
        for gk, ga, gb in defs:
            gt, _ = gq.parse(gq.tokens(gb)); gq.lams(gt, 1, L)
        P = name
        keys = [gk for gk, ga, gb in defs] + ['(wadd dcbase %s)' % li for li, ld, lb in L]
        FT = '(q-ft (fr-tab %s %s-T) (fr-tab %s %s-GT) %s-D %s-A)' % (R, P, R, P, P, P)
        MQ = '(fc-to-fq %d (fr-bu %s (dconv %s-m)))' % (k, R, P)
        ks = 'nil'
        for kk in reversed(keys): ks = '(cons %s %s)' % (kk, ks)
        o.append('-- %s: the C link' % P)
        o.append('%s-ks : List Word' % P)
        o.append('%s-ks = %s' % (P, ks))
        o.append('%s-df : Word → Bool' % P)
        o.append('%s-df g = kmem g %s-ks' % (P, P))
        o.append('%s-AN : Word → Nat' % P)
        o.append('%s-AN g = if wlt g dcbase then dnat (%s-A g) else (if wlt g dclbase then suc (%s-D (wsub g dcbase)) else dnat (%s-A g))' % (P, P, P, P))
        o.append('%s-GC : Word → CA' % P)
        o.append('%s-GC g = fq-to-ca (%s g) ckt (%s-AN g)' % (P, FT, P))
        o.append('%s-tok : (g : Word) → %s-df g ≡ true → ca-ok %s-AN %s-df (%s g) ckt ≡ true' % (P, P, P, P, FT))
        o.append('%s-tok = keys-ok (λ g → ca-ok %s-AN %s-df (%s g) ckt) %s-ks (λ j → true)' % (P, P, P, FT, P))
        xs = ['x%d' % j for j in range(1, k + 1)]; vs = ['v%d' % j for j in range(1, k + 1)]
        qa = 'qa0'
        for j in range(k): qa = '(qa1 %s %s %s)' % (xs[j], vs[j], qa)
        ev = 'kqnil'
        for j in range(k): ev = '(kqcons %s %s)' % (vs[j], ev)
        binds = ''.join(' (%s : DV) (%s : KQ)' % (xs[j], vs[j]) for j in range(k))
        o.append('-- the checked path to the C: at every fuel, whatever the source computes at the arguments, the first-order')
        o.append('-- form computes (refined), and the C computes what the first-order form does (refined), in every refining scope')
        o.append('%s-cpath : (n : Nat)%s (m : Nat) (s : CS) → qa-ok %s-D %s-T %s → Corr %s-AN %s-df %d %s s' % (P, binds, P, P, qa, P, P, k, ev))
        o.append('  → qrel %s-D (derase (dsev %s-G n %s-m (qa-ρ %s))) (evq %s (fr-addn n m) %s %s)' % (P, P, P, qa, FT, MQ, ev))
        o.append('    × CR %s-AN %s-df (evq %s (fr-addn n m) %s %s) (evc %s-GC %s-AN %s-df (fr-addn n m) (fq-to-ca %s ckt %d) s)' % (P, P, FT, MQ, ev, P, P, P, MQ, k))
        o.append('%s-cpath n%s m s ha hc = ca-path-n std-frule %s-G %s-T %s-GT %s-gok %s-D %s-A %s-gq %s-AN %s-df %s-df %s-GC (λ g h → h) %s-tok (λ g h → λ i → %s-GC g) n %s-m %s m s (dtok-auto %s-T %s-m (λ j → true)) ha (λ j → true) (λ j → true) hc' % (
            P, ''.join(' %s %s' % (xs[j], vs[j]) for j in range(k)), P, P, P, P, P, P, P, P, P, P, P, P, P, P, qa, P, P))
        # what the proved route prints is the instance's C: each function of the printed table
        T = qtab(name, sp)
        o.append('#same ca-table (ca-tr-defs (%s)) #0 = fq-to-ca %s ckt %d' % (T, MQ, k))
        for kk in keys:
            o.append('#same ca-table (ca-tr-defs (%s)) %s = %s-GC %s' % (T, kk if not kk.startswith('(wadd') else kk.replace('wadd dcbase', '%wadd dc-base'), P, kk))
        # the C's meaning computes run.py's answer at its arguments (the harness's main calling the program's)
        if fargs:
            args = 'lnil'
            for a in reversed(fargs): args = '(lcons (%s) %s)' % (a, args)
            H = 'ca-harness (fo-args-fq %s) (%s)' % (args, T)
        else:
            H = 'ca-tr-defs (%s)' % T
        o.append('#same evc (ca-table (%s)) (ca-arity (%s)) (ca-disp (%s)) (dnat #64) (cacall #0 canil) csnil = cw #%s' % (H, H, H, expect))
    return '\n'.join(o) + '\n'

if __name__ == '__main__':
    sys.stdout.write(gen())
