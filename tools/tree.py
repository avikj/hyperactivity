#!/usr/bin/env python3
# tools/tree.py — the bird's-eye view, generated from the repository: every .cub under lib/ and
# experiments/, every C file under src/, every tool; for each its first header line, its size,
# whether `make library` checks it, and every top-level construct it defines (data types,
# codata, records, definitions with signatures, unsigned definitions, primitives/postulates).
# Run from scoped-machine/:  python3 tools/tree.py   (prints the index; nothing is stored)
import os, re, subprocess, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)
lib = subprocess.run(['make', '-s', '-n', 'library'], capture_output=True, text=True).stdout
inlib = set(re.findall(r'(lib/\S+\.cub)', lib))
def header(path):
    with open(path, errors='replace') as f:
        for line in f:
            s = line.strip()
            if s.startswith('--') or s.startswith('/*') or s.startswith('#'):
                s = s.lstrip('-/*# ').strip()
                if s: return s[:160]
            elif s: return ''
    return ''
def constructs(path):
    data, sig, unsig, prim = [], [], [], []
    seen = set()
    with open(path, errors='replace') as f:
        lines = f.read().split('\n')
    for i, line in enumerate(lines):
        m = re.match(r'^(data|codata|record)\s+(\S+)', line)
        if m: data.append(f'{m.group(1)} {m.group(2)}'); continue
        m = re.match(r'^(primitive|postulate|foreign)\s+(\S+)', line)
        if m: prim.append(f'{m.group(1)} {m.group(2)}'); continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_'·-]*)\s+:\s", line)
        if m: sig.append(m.group(1)); seen.add(m.group(1)); continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_'·-]*)\b[^:]*=", line)
        if m and m.group(1) not in seen and not line.startswith(('import', '#')):
            seen.add(m.group(1)); unsig.append(m.group(1))
    unsig = [u for u in unsig if u not in sig]
    return data, sig, unsig, prim
out = ['# The repository, file by file (generated by `tools/tree.py`; do not edit by hand)', '',
       'For each file: lines, whether `make library` checks it ([lib] or [not in library]), its first',
       'header line, then its constructs: data/codata/record types, definitions with a signature,',
       'definitions without one (only legal in the bootstrap files prelude code match nav cost lin',
       'check), primitives/postulates/foreign (only legal in prim, std). Open findings are tickets',
       '(`python3 tools/work.py list`).', '']
dirs = [('lib', '.cub'), ('experiments', '.cub'), ('src', ('.c', '.h')), ('tools', ('.py', '.sh'))]
for d, ext in dirs:
    out.append(f'## {d}/'); out.append('')
    for dp, dn, fn in sorted(os.walk(d)):
        dn.sort()
        for f in sorted(fn):
            if not f.endswith(ext): continue
            p = os.path.join(dp, f)
            n = sum(1 for _ in open(p, errors='replace'))
            tag = '' if not p.endswith('.cub') or d != 'lib' else (' [lib]' if p in inlib else ' [not in library]')
            out.append(f'### `{p}` — {n} lines{tag}')
            h = header(p)
            if h: out.append(f'{h}')
            if p.endswith('.cub'):
                data, sig, unsig, prim = constructs(p)
                if data: out.append('- types: ' + ', '.join(data))
                if prim: out.append('- primitive/postulate/foreign: ' + ', '.join(prim))
                if sig: out.append(f'- definitions ({len(sig)}): ' + ', '.join(sig))
                if unsig: out.append(f'- without signature ({len(unsig)}): ' + ', '.join(unsig))
            out.append('')
print('\n'.join(out))
