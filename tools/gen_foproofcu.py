# term tests/foproofm.cub reads (every construct and primitive the printers emit): evcu on CA's embedding
# (ca-cu) is evc; the checked translation fq-to-cu (at tables cv-S: a direct call's parameters and result
# words, a closure's target boxed) has evc's value under evcu, is fq-to-ca once its conversions are erased
