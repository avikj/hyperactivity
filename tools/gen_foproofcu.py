# accepted (cu-wt), its bodies erased equal to the boxed link's (ca-harness's), and evcu's value of the
# harness's main run.py's answer.
# To rerun (after tests/foproofm.cub's terms or run.py's proved programs change): from scoped-machine/,
# `python3 tools/gen_foproofcu.py > tests/foproofcu.cub`.
