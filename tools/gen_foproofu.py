#!/usr/bin/env python3
# tests/foproofu-progs.cub: for every program of experiments/fo/run.py's proved-* programs (the data route's,
# as tools/gen_foproofq.py lists them), the kinds of its first-order table (lib/foproofu.cub, U1): the tables
# inferred (kinfer: from the keys' bodies, the main and the harness's arguments), decided by kok over the
# main and every key (kkeys-ok), and kind-sound instantiated (P-ksound: at every fuel, a term meeting the
# conditions in an environment of its kinds has its kind). Builds on tests/foproofq-progs.cub's tables and
# the table's keys as tools/gen_foproofc.py lists them (P-uks, P-udf, P-uAN: its P-ks, P-df, P-AN under
# names of their own, so this file loads without tests/foproofc-progs.cub).
# To rerun (after a program or the mirror changes): `python3 tools/gen_foproofu.py > tests/foproofu-progs.cub`
# from scoped-machine/ with build/cubical built (it reruns tools/gen_foproofq.py's machine readings).
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_foproofq as gq
import re, subprocess
# data types' indices, read by the machine (didx is untyped; each index is pinned by a reading in the
# generated file, so a shift in the libraries fails there, not in kok)
def didx_of(names):
    probe = gq.PRELUDE + ''.join('#show didx (code %s)\n' % n for n in names)
    path = '/tmp/gen_foproofu_probe.cub'
    open(path, 'w').write(probe)
    libs = [os.path.join(gq.ROOT, 'lib', l + '.cub') for l in gq.LIBS]
    env = dict(os.environ, CUBICAL_WORKERS='0', CUBICAL_NOCACHE='1')
    out = subprocess.run([os.path.join(gq.ROOT, 'build', 'cubical')] + libs + [path], capture_output=True, text=True, env=env).stdout
    lines = out.split('\n'); res = []
    for j, l in enumerate(lines):
        if l.startswith('didx') and j + 1 < len(lines) and lines[j + 1].lstrip().startswith('= '):
            res.append(re.sub(r'\s*\[[^\]]*\]\s*$', '', lines[j + 1].strip()[2:]))
    if len(res) != len(names): sys.exit('gen_foproofu: %d indices for %d data types:\n%s' % (len(res), len(names), out[-2000:]))
    return dict(zip(names, res))

# the harness's arguments' kinds, from the program's declared parameter types (a word kw; a pair, data type
# 0, kdc #0; any other data type D kdc (didx (code D))), or from the argument (a literal kw, a constructor
# fcon X ... kdc X) where no type is declared
def arg_kind(T, a):
    if T is not None:
        T = T.strip()
        if T == 'Word': return 'kw'
        if '×' in T: return 'kdc #0'
        return ('data', T)
    if a.startswith('flit '): return 'kw'
    if a.startswith('fcon '):
        t = gq.unwrap(gq.parse(gq.tokens(a))[0]); x = gq.text(gq.args(t)[0])
        m = re.match(r'\(?didx \(code (\S+)\)\)?$', x)
        return ('data', m.group(1)) if m else 'kdc %s' % x
    return 'ka'
def param_types(sp):
    m = re.match(r'dc-prog \(normalize \((.*?)\) ', sp[0])
    if not m: return None
    ts = m.group(1).split('→')[:-1]
    return ts
def gen():
    probe = gq.PRELUDE + ''.join('#show %s\n' % p[1][0] for p in gq.PROGS)
    readings = gq.run_machine(probe)
    allk = []
    for (name, sp, fargs, expect) in gq.PROGS:
        ts = param_types(sp)
        allk += [arg_kind(ts[j] if ts and j < len(ts) else None, a) for j, a in enumerate(fargs)]
    DI = didx_of(sorted(set(k[1] for k in allk if isinstance(k, tuple))))
    kd = lambda k: 'kdc %s' % DI[k[1]] if isinstance(k, tuple) else k
    R = '(fst std-frule)'
    o = ['-- generated by tools/gen_foproofu.py (do not edit: rerun it); loaded after tests/foproofq-progs.cub']
    o.append('-- the data types\' indices the kinds name (a shift in the libraries fails here: rerun the generator)')
    for n in sorted(DI): o.append('#same didx (code %s) = %s' % (n, DI[n]))
    for (name, sp, fargs, expect), r in zip(gq.PROGS, readings):
        t = gq.unwrap(gq.parse(gq.tokens(r))[0])
        tup = gq.unwrap(gq.args(t)[0])
        K, main, gs = [gq.unwrap(x) for x in tup[1]]
        k = int(gq.text(K).lstrip('#'))
        defs = []
        g = gs
        while gq.head(g) == 'lcons':
            e = gq.unwrap(gq.args(g)[0])
            gk, ga, gb = [gq.unwrap(x) for x in e[1]]
            defs.append((gq.text(gk), gq.text(ga), gq.text(gb)))
            g = gq.args(g)[1]
        L = []
        gq.lams(main, k, L)
        for gk, ga, gb in defs:
            gt, _ = gq.parse(gq.tokens(gb)); gq.lams(gt, 1, L)
        keys = [gk for gk, ga, gb in defs] + ['(wadd dcbase %s)' % li for li, ld, lb in L]
        ks = 'nil'
        for kk in reversed(keys): ks = '(cons %s %s)' % (kk, ks)
        P = name
        FT = '(q-ft (fr-tab %s %s-T) (fr-tab %s %s-GT) %s-D %s-A)' % (R, P, R, P, P, P)
        MQ = '(fc-to-fq %d (fr-bu %s (dconv %s-m)))' % (k, R, P)
        if fargs:
            mk = 'knil'
            ts = param_types(sp)
            ks_ = [arg_kind(ts[j] if ts and j < len(ts) else None, a) for j, a in enumerate(fargs)]
            for kk in reversed(ks_): mk = '(kcons (%s) %s)' % (kd(kk), mk)
        else:
            mk = 'knil'
        o.append('-- %s: the kinds of its first-order table' % P)
        o.append('%s-uks : List Word' % P)
        o.append('%s-uks = %s' % (P, ks))
        o.append('%s-udf : Word → Bool' % P)
        o.append('%s-udf g = kmemu g %s-uks' % (P, P))
        o.append('%s-uAN : Word → Nat' % P)
        o.append('%s-uAN g = if wlt g dcbase then dnat (%s-A g) else (if wlt g dclbase then suc (%s-D (wsub g dcbase)) else dnat (%s-A g))' % (P, P, P, P))
        o.append('%s-MK : Kd' % P)
        o.append('%s-MK = %s' % (P, mk))
        o.append('%s-S : KS' % P)
        o.append('%s-S = kinfer %s %s-uks %s-uAN %s %s-MK' % (P, FT, P, P, MQ, P))
        o.append('#same kkeys-ok %s-S %s-udf %s %s-uks = true' % (P, P, FT, P))
        o.append('#same kok %s-S %s-udf %s kmt (kpush %s-MK (λ n → ka)) = true' % (P, P, MQ, P))
        o.append('#show ksyn %s-S %s kmt (kpush %s-MK (λ n → ka))' % (P, MQ, P))
        o.append('%s-ksound : (n : Nat) → KThm %s-S %s-udf %s n' % (P, P, P, FT))
        o.append('%s-ksound = kind-sound %s-S %s-udf %s (λ g h → andl (kok %s-S %s-udf (%s g) kmt (spk %s-S g)) (kle (ksyn %s-S (%s g) kmt (spk %s-S g)) (ks-SR %s-S g)) (kkeys-ok-k %s-S %s-udf %s %s-uks (λ i → true) g h)) (λ g h → andr (kok %s-S %s-udf (%s g) kmt (spk %s-S g)) (kle (ksyn %s-S (%s g) kmt (spk %s-S g)) (ks-SR %s-S g)) (kkeys-ok-k %s-S %s-udf %s %s-uks (λ i → true) g h))' % (
            P, P, P, FT, P, P, FT, P, P, FT, P, P, P, P, FT, P, P, P, FT, P, P, FT, P, P, P, P, FT, P))
        # the main's value at fuel n has the main's kind, in an environment of the arguments' kinds
        o.append('%s-kmain : (n : Nat) (e : KQ) → EnvK (ks-T %s-S) (kpush %s-MK (λ n → ka)) e → Kv (ks-T %s-S) (ksyn %s-S %s kmt (kpush %s-MK (λ n → ka))) (evq %s n %s e)' % (P, P, P, P, P, MQ, P, FT, MQ))
        o.append('%s-kmain n e he = %s-ksound n %s kmt (kpush %s-MK (λ n → ka)) e (λ i → true) he' % (P, P, MQ, P))
    return '\n'.join(o) + '\n'

if __name__ == '__main__':
    sys.stdout.write(gen())
