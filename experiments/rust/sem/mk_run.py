#!/usr/bin/env python3
"""mk_run.py CRATE-NAME MSG-SIZE COUNT MESSAGES.bin ANSWERS.txt > out.cub — a diagnostic input for
experiments/rust/sem/run.cub (tracks/R-rust.md, "Diagnostics"): the first COUNT messages of
MESSAGES.bin (MSG-SIZE bytes each) as lists of bytes, the answers the rustc-built binary printed
for them (ANSWERS.txt, one signed integer per line) as 64-bit words, and the command that reads
the crate's entry on the messages and compares."""
import sys

def main():
    name, size, count = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    data = open(sys.argv[4], 'rb').read()
    answers = [int(x) for x in open(sys.argv[5]).read().split()][:count]
    out = ['-- generated by experiments/rust/sem/mk_run.py: %d messages of %d bytes for %s-crate' % (count, size, name)]
    names = []
    for i in range(count):
        m = data[size * i:size * (i + 1)]
        s = 'nil'
        for b in reversed(m):
            s = '(cons #%d %s)' % (b, s)
        out.append('%s-rd-m%d : List Word\n%s-rd-m%d = %s' % (name, i, name, i, s))
        names.append('%s-rd-m%d' % (name, i))
    def lst(xs):
        s = 'nil'
        for x in reversed(xs):
            s = '(cons %s %s)' % (x, s)
        return s
    out.append('%s-rd-msgs : List (List Word)\n%s-rd-msgs = %s' % (name, name, lst(names)))
    out.append('%s-rd-answers : List Word\n%s-rd-answers = %s' % (name, name, lst(['#%d' % (a % 2**64) for a in answers])))
    if '--pairs' in sys.argv:
        # an entry of two 64-bit integers: each record is the two, little-endian
        ps = lst(['(#%d , #%d)' % (int.from_bytes(data[16 * i:16 * i + 8], 'little'), int.from_bytes(data[16 * i + 8:16 * i + 16], 'little')) for i in range(count)])
        out = out[:1] + ['%s-rd-pairs : List (Word × Word)\n%s-rd-pairs = %s' % (name, name, ps), out[-1]]
        out.append('#show rd-run2 %s-crate #100000 %s-rd-pairs' % (name, name))
        out.append('#same rd-run2 %s-crate #100000 %s-rd-pairs = mok (c-val %s-rd-answers)' % (name, name, name))
    else:
        out.append('#show rd-run %s-crate #100000 #%d %s-rd-msgs' % (name, size, name))
        out.append('#same rd-run %s-crate #100000 #%d %s-rd-msgs = mok (c-val %s-rd-answers)' % (name, size, name, name))
    print('\n'.join(out))

main()
